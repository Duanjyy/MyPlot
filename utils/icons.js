/* ---------- 渲染 & 缓存 ---------- */
const cache = {};
function render(name, color) {
  const key = name + '|' + color;
  if (cache[key]) return cache[key];
  const markup = P[name] ? P[name].split('COL').join(color) : '';
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">' + markup + '</svg>';
  const uri = 'data:image/svg+xml;base64,' + b64(svg);
  cache[key] = uri;
  return uri;
}

